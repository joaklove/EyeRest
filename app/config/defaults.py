# ---------------------------------------------------------------------------
# 屏幕暴露会话（Screen Exposure Session）—— V1.0 核心
#
# 设计原则：键鼠无操作 ≠ 眼睛没在看屏幕。
# 看 PDF / 视频 / 代码 / 思考时可以几分钟不动键鼠，但眼睛一直在工作。
# 因此 GetLastInputInfo 只作为"是否离开电脑"的辅助信号，
# 不再作为"是否在用眼"的判据。
# ---------------------------------------------------------------------------
# 无输入超过该时长 → 进入 AWAY（暂停累计暴露，但**不重置**计时器）
AWAY_THRESHOLD = 180
